"""ANSI C Code Exporter for Decision Tree IDS.

Translates trained scikit-learn decision trees into standalone ANSI C source code,
enabling zero-overhead integer inference on automotive microcontrollers.
"""

from __future__ import annotations

import math
import os
import subprocess
from typing import List, Tuple
import numpy as np
from sklearn.tree import _tree

from src.detection.decision_tree import CANFDDecisionTree
from src.features.frame_features import FEATURE_NAMES


class CCodeExporter:
    """Exports Decision Tree models to standalone, verifiable ANSI C code."""

    def __init__(self, dt_wrapper: CANFDDecisionTree) -> None:
        self.model = dt_wrapper.model
        self.classes_ = self.model.classes_

    def generate_c_source(self) -> str:
        """Generate complete ANSI C source code for classify_frame_array."""
        tree = self.model.tree_

        code_lines = [
            '#include "classifier.h"',
            "",
            "/* Autogenerated CAN-FD Decision Tree Classifier (Zero Floating-Point) */",
            "int classify_frame_array(const int64_t *f) {",
            "    (void)f; /* Suppress unused parameter warning for trivial single-leaf trees */",
        ]

        def recurse(node: int, depth: int) -> None:
            indent = "    " * depth
            if tree.children_left[node] == _tree.TREE_LEAF:
                # Leaf node: determine majority class
                class_idx = int(np.argmax(tree.value[node][0]))
                predicted_class = int(self.classes_[class_idx])
                code_lines.append(f"{indent}return {predicted_class};")
            else:
                feat_idx = tree.feature[node]
                feat_name = FEATURE_NAMES[feat_idx]
                threshold_val = int(math.floor(tree.threshold[node]))

                code_lines.append(
                    f"{indent}if (f[{feat_idx}] <= {threshold_val}LL) /* {feat_name} <= {threshold_val} */ {{"
                )
                recurse(tree.children_left[node], depth + 1)
                code_lines.append(f"{indent}}} else {{")
                recurse(tree.children_right[node], depth + 1)
                code_lines.append(f"{indent}}}")

        recurse(0, 1)
        code_lines.append("}")
        code_lines.append("")

        # Convenience wrapper unpacking named arguments
        params_str = ", ".join(f"int64_t {name}" for name in FEATURE_NAMES)
        args_str = ", ".join(FEATURE_NAMES)
        code_lines.extend(
            [
                f"int classify_frame({params_str}) {{",
                f"    const int64_t f[{len(FEATURE_NAMES)}] = {{{args_str}}};",
                "    return classify_frame_array(f);",
                "}",
                "",
            ]
        )

        return "\n".join(code_lines)

    def generate_header(self) -> str:
        """Generate ANSI C header file."""
        params_str = ", ".join(f"int64_t {name}" for name in FEATURE_NAMES)
        return f"""#ifndef CANFD_CLASSIFIER_H
#define CANFD_CLASSIFIER_H

#include <stdint.h>

#define NUM_FEATURES {len(FEATURE_NAMES)}

int classify_frame_array(const int64_t *features);
int classify_frame({params_str});

#endif /* CANFD_CLASSIFIER_H */
"""

    def generate_test_harness(self) -> str:
        """Generate C main test harness reading vectors from stdin."""
        return """#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include "classifier.h"

int main(void) {
    int64_t f[NUM_FEATURES];
    while (1) {
        int read_count = 0;
        for (int i = 0; i < NUM_FEATURES; i++) {
            long long val;
            if (scanf("%lld", &val) == 1) {
                f[i] = (int64_t)val;
                read_count++;
            } else {
                break;
            }
        }
        if (read_count == NUM_FEATURES) {
            int pred = classify_frame_array(f);
            printf("%d\\n", pred);
        } else {
            break;
        }
    }
    return 0;
}
"""

    def export(self, output_dir: str = "models/exported") -> tuple[str, str, str]:
        """Export header, source, and test harness files to output_dir."""
        os.makedirs(output_dir, exist_ok=True)
        h_path = os.path.join(output_dir, "classifier.h")
        c_path = os.path.join(output_dir, "classifier.c")
        test_path = os.path.join(output_dir, "test_harness.c")

        with open(h_path, "w", encoding="utf-8") as f:
            f.write(self.generate_header())
        with open(c_path, "w", encoding="utf-8") as f:
            f.write(self.generate_c_source())
        with open(test_path, "w", encoding="utf-8") as f:
            f.write(self.generate_test_harness())

        return h_path, c_path, test_path

    def compile_and_verify(
        self,
        X_test: np.ndarray,
        y_expected: np.ndarray,
        output_dir: str = "models/exported",
    ) -> float:
        """Compile C files using GCC and verify 100% equivalence on test samples.

        Returns:
            agreement_rate (float): 1.0 for 100% agreement.
        """
        self.export(output_dir=output_dir)
        bin_path = os.path.join(output_dir, "c_classifier")
        c_path = os.path.join(output_dir, "classifier.c")
        test_path = os.path.join(output_dir, "test_harness.c")

        # Compile with GCC
        cmd = ["gcc", "-O2", c_path, test_path, "-o", bin_path]
        compile_res = subprocess.run(cmd, capture_output=True, text=True)
        if compile_res.returncode != 0:
            raise RuntimeError(f"GCC Compilation failed: {compile_res.stderr}")

        # Format test features as space-separated integers
        input_data = "\n".join(" ".join(str(int(val)) for val in row) for row in X_test) + "\n"

        run_res = subprocess.run([bin_path], input=input_data, capture_output=True, text=True)
        if run_res.returncode != 0:
            raise RuntimeError(f"C Classifier execution failed: {run_res.stderr}")

        c_preds = [int(line.strip()) for line in run_res.stdout.strip().split("\n") if line.strip()]
        if len(c_preds) != len(y_expected):
            raise ValueError(f"Output count mismatch: C returned {len(c_preds)}, expected {len(y_expected)}")

        matches = sum(1 for c_p, py_p in zip(c_preds, y_expected) if c_p == py_p)
        return float(matches / len(y_expected))
